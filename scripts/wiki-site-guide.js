    const cat = await wiki.getCategoryBySlug(CATEGORY_SLUG)
        || await wiki.createCategory({ name: CATEGORY_NAME, slug: CATEGORY_SLUG, description: '官网各个功能的使用说明：集市交易、贡献点、商城、支付、成员档案、Wiki 投稿等' }, AUTHOR_ID);
